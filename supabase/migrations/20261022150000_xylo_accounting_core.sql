create table if not exists public.accounts (
 id uuid primary key default gen_random_uuid(), business_id uuid not null references public.businesses(id) on delete cascade,
 code text not null, name text not null, account_type text not null check (account_type in ('asset','liability','equity','income','expense')),
 normal_balance text not null check (normal_balance in ('debit','credit')), is_system boolean not null default false, is_active boolean not null default true,
 created_at timestamptz not null default now(), unique (business_id, code)
);
create table if not exists public.journal_entries (
 id uuid primary key default gen_random_uuid(), business_id uuid not null references public.businesses(id) on delete cascade,
 entry_number bigint generated by default as identity, entry_date date not null default current_date, reference text, description text not null,
 status text not null default 'draft' check (status in ('draft','posted','void')), created_by uuid not null default auth.uid() references auth.users(id),
 posted_at timestamptz, created_at timestamptz not null default now(), unique (business_id, entry_number)
);
create table if not exists public.journal_lines (
 id uuid primary key default gen_random_uuid(), journal_entry_id uuid not null references public.journal_entries(id) on delete cascade,
 account_id uuid not null references public.accounts(id), description text, debit numeric(14,2) not null default 0 check (debit >= 0),
 credit numeric(14,2) not null default 0 check (credit >= 0), created_at timestamptz not null default now(),
 check ((debit > 0 and credit = 0) or (credit > 0 and debit = 0))
);
create index if not exists journal_entries_business_date_idx on public.journal_entries(business_id, entry_date desc);
create index if not exists journal_lines_entry_idx on public.journal_lines(journal_entry_id);
create index if not exists journal_lines_account_idx on public.journal_lines(account_id);
create table if not exists public.inventory_items (
 id uuid primary key default gen_random_uuid(), business_id uuid not null references public.businesses(id) on delete cascade,
 sku text, name text not null, description text, unit text not null default 'unit', quantity numeric(14,3) not null default 0,
 reorder_level numeric(14,3) not null default 0, unit_cost numeric(14,2) not null default 0, is_active boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(), unique (business_id, sku),
 check (quantity >= 0), check (reorder_level >= 0), check (unit_cost >= 0)
);
create table if not exists public.stock_movements (
 id uuid primary key default gen_random_uuid(), business_id uuid not null references public.businesses(id) on delete cascade,
 item_id uuid not null references public.inventory_items(id) on delete cascade, movement_date date not null default current_date,
 movement_type text not null check (movement_type in ('opening','purchase','sale','adjustment_in','adjustment_out','return_in','return_out')),
 quantity numeric(14,3) not null check (quantity > 0), unit_cost numeric(14,2) not null default 0 check (unit_cost >= 0),
 reference text, notes text, created_by uuid not null default auth.uid() references auth.users(id), created_at timestamptz not null default now()
);
alter table public.accounts enable row level security;
alter table public.journal_entries enable row level security;
alter table public.journal_lines enable row level security;
alter table public.inventory_items enable row level security;
alter table public.stock_movements enable row level security;
drop policy if exists "Owners manage business accounts" on public.accounts;
create policy "Owners manage business accounts" on public.accounts for all to authenticated
using (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())))
with check (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())));
drop policy if exists "Owners manage journal entries" on public.journal_entries;
create policy "Owners manage journal entries" on public.journal_entries for all to authenticated
using (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())))
with check (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())));
drop policy if exists "Owners manage journal lines" on public.journal_lines;
create policy "Owners manage journal lines" on public.journal_lines for all to authenticated
using (exists (select 1 from public.journal_entries je join public.businesses b on b.id=je.business_id where je.id=journal_entry_id and b.owner_id=(select auth.uid())))
with check (
 exists (select 1 from public.journal_entries je join public.businesses b on b.id=je.business_id where je.id=journal_entry_id and b.owner_id=(select auth.uid()))
 and exists (select 1 from public.journal_entries je join public.accounts a on a.business_id=je.business_id where je.id=journal_entry_id and a.id=account_id)
);
drop policy if exists "Owners manage inventory items" on public.inventory_items;
create policy "Owners manage inventory items" on public.inventory_items for all to authenticated
using (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())))
with check (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())));
drop policy if exists "Owners manage stock movements" on public.stock_movements;
create policy "Owners manage stock movements" on public.stock_movements for all to authenticated
using (exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid())))
with check (
 exists (select 1 from public.businesses b where b.id=business_id and b.owner_id=(select auth.uid()))
 and exists (select 1 from public.inventory_items i where i.id=item_id and i.business_id=business_id)
);
grant select, insert, update, delete on public.accounts, public.journal_entries, public.journal_lines, public.inventory_items, public.stock_movements to authenticated;
